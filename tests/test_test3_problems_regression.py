class TestCookieModInsideBookChapterFolder:
    """Verify that the on-disk folder structure has the cookie_mod
    files in the SAME folder as the chapter's index.html.
    """

    def test_cookie_mod_and_chapter_share_same_gen_path(self):
        """Both the chapter's index.html AND the chapter's cookie_mod
        video should be saved in the same on-disk folder
        (chapter's *NN* folder, e.g. *02* 2. Week Overview/).
        """
        from moodle_dl.downloader.task_file_ops import TaskFileOps
        from moodle_dl.types import File, Course

        course = Course(_id=1, fullname='Test Course')
        ops = TaskFileOps(MagicMock())

        # Chapter index.html
        index_html = File(
            module_id=7342416, section_id=1,
            section_name='Week 2',             module_name='2. Week Overview', module_modname='book',
            content_filepath='/2. Week Overview/',
            content_filename='index.html',
            content_fileurl='https://example.com/2/index.html',
            content_type='file',
            content_isexternalfile=False,
            content_filesize=1024,
            content_timemodified=1700000000,
        )
        index_html.position_in_section = 1  # chapter's position in book
        setattr(index_html, '_module_has_attachments', True)
        setattr(index_html, '_in_module_folder', True)

        # Chapter's cookie_mod video
        kaltura = File(
            module_id=7342416, section_id=1,
            section_name='Week 2',             module_name='2. Week Overview', module_modname='cookie_mod-kalvidres',
            content_filepath='/2. Week Overview/',
            content_filename='Week Overview - Video.mp4',
            content_fileurl='https://example.com/video.mp4',
            content_type='cookie_mod',
            content_isexternalfile=True,
            content_filesize=1024000,
            content_timemodified=1700000000,
        )
        kaltura.position_in_section = 1  # SAME position as chapter
        setattr(kaltura, '_module_has_attachments', True)
        setattr(kaltura, '_in_module_folder', True)

        path_index = ops.gen_path('/storage', course, index_html)
        path_kaltura = ops.gen_path('/storage', course, kaltura)

        # BOTH should be in the same folder
        # The folder should have the chapter's *NN* prefix (e.g. *02*)
        # not the cookie_mod's separate position (e.g. *01*)
        folder_index = path_index.rsplit('/', 1)[0] if path_index.endswith('index.html') else path_index
        folder_kaltura = path_kaltura.rsplit('/', 1)[0] if path_kaltura.endswith('Video.mp4') else path_kaltura

        # Both folders should have the same name
        assert folder_index == folder_kaltura, (
            f'Chapter index.html and cookie_mod video should be in the '
            f'same folder. Got: index.html folder={folder_index!r}, '
            f'kaltura folder={folder_kaltura!r}'
        )
        # The folder should NOT have *01* prefix (which would mean
        # the cookie_mod got its own position 0)
        folder_name = folder_kaltura.rsplit('/', 1)[-1]
        assert not folder_name.startswith('*01*') or 'Week' in folder_name, (
            f'Folder should not be *01* Week (cookie_mod collision). '
            f'Got: {folder_name!r}'
        )


