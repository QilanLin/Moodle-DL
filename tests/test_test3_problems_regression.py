class TestChapterMappingHasOnDiskFolderName:
    """When book.py builds chapter_mapping (the data structure
    passed to _create_linked_print_book_html), the folder_name
    should be the on-disk name (with *NN* prefix), not the raw
    chapter folder name.

    Real case (test3): book.py:303 sets
      'folder_name': chapter_folder_name
    where chapter_folder_name comes from _format_chapter_folder_name,
    which returns the raw chapter name (e.g. '2. Week Overview')
    WITHOUT the *NN* prefix.

    The actual on-disk folder is *02* 2. Week Overview/ (with prefix).

    This is the root cause of Problem 3 (videos don't render) and
    also affects Problem 2 (TOC links).
    """

    def test_format_chapter_folder_name_returns_raw_name(self):
        """Pin the current behavior of _format_chapter_folder_name:
        it returns the raw chapter name WITHOUT *NN* prefix.

        This is the root cause of Problems 2 and 3.
        """
        from moodle_dl.moodle.mods.book import BookMod
        # When chapter_number is set (Moodle's own numbering)
        result = BookMod._format_chapter_folder_name(
            chapter_title='Week Overview',
            chapter_number='1.1',
            fallback_index=0,
        )
        # Current behavior: returns '1.1 Week Overview' (no *NN* prefix)
        assert result == '1.1 Week Overview', (
            f'_format_chapter_folder_name returns raw chapter name. '
            f'This causes Problems 2 and 3. Got: {result!r}'
        )

    def test_format_chapter_folder_name_with_fallback(self):
        """Pin the current behavior with no chapter_number (uses
        fallback_index).
        """
        from moodle_dl.moodle.mods.book import BookMod
        result = BookMod._format_chapter_folder_name(
            chapter_title='Week Overview',
            chapter_number='',
            fallback_index=2,
        )
        # Current behavior: '02 - Week Overview' (no *NN* prefix)
        assert result == '02 - Week Overview', (
            f'_format_chapter_folder_name with fallback. Got: {result!r}'
        )


